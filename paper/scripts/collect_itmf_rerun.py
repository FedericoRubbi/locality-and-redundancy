import csv
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "itmf_rerun"
DATASETS = ["MNIST", "F-MNIST", "CIFAR10", "CIFAR100"]
LABELS = {"bp": r"BP, same size (this work)", "itmf": r"\itmf{} (this work)"}


def load(phase):
    return [(f, json.loads(f.read_text())) for f in sorted((RAW / phase).glob("*.json"))]


def write_csv(path, rows):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    print(f"{path.relative_to(ROOT)}: {len(rows)} rows")


def main():
    final, search = load("final"), load("search")
    rows, blocks = [], []
    for f, r in final:
        src = str(f.relative_to(ROOT)).replace("\\", "/")
        prov = r["provenance"]
        rows.append({"method": r["method"], "dataset": r["dataset"], "seed": r["seed"],
                     "test_acc": round(r["final_acc"], 2), "epochs": r["epochs"],
                     "selection": prov["source"], "selected_trial": prov.get("trial"),
                     "selection_acc": round(prov.get("val_acc", prov.get("recorded_test_acc")), 2),
                     "config": json.dumps(r["config"], sort_keys=True), "source": src})
        for b, acc in enumerate(r["history"]["layer_acc"][-1], start=1):
            blocks.append({"method": r["method"], "dataset": r["dataset"], "seed": r["seed"], "block": b,
                           "test_acc": round(acc, 2), "source": src})
    write_csv(ROOT / "data" / "itmf_rerun.csv", rows)
    write_csv(ROOT / "data" / "itmf_rerun_blocks.csv", blocks)
    write_csv(ROOT / "data" / "itmf_rerun_search.csv", [
        {"method": r["method"], "dataset": r["dataset"], "trial": r["trial"], "val_acc": round(r["final_acc"], 2),
         "config": json.dumps(r["config"], sort_keys=True),
         "source": str(f.relative_to(ROOT)).replace("\\", "/")} for f, r in search])

    lines = ["% Generated by scripts/collect_itmf_rerun.py from data/itmf_rerun.csv; do not edit by hand.",
             r"\newcommand{\itmfRerunRows}{%"]
    means = {(m, d): statistics.mean([row["test_acc"] for row in rows if row["method"] == m and row["dataset"] == d])
             for m in ("bp", "itmf") for d in DATASETS}
    for method in ("bp", "itmf"):
        cells = []
        for d in DATASETS:
            accs = [row["test_acc"] for row in rows if row["method"] == method and row["dataset"] == d]
            if len(accs) >= 2:
                cell = f"{statistics.mean(accs):.2f} \\pm {statistics.stdev(accs):.2f}"
                best = means[(method, d)] == max(means[(m, d)] for m in ("bp", "itmf"))
                cells.append(f"$\\mathbf{{{cell}}}$" if best else f"${cell}$")
            else:
                cells.append(r"\missing{n/a}")
        lines.append(f"  {LABELS[method]} & " + " & ".join(cells) + r" \\")
    lines.append("}")
    out = ROOT / "tables" / "itmf_rerun_rows.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
