@lru_cache(maxsize=None)
def load(name):
    with open(DATA / name, newline="", encoding="utf-8") as fh:
        return tuple(csv.DictReader(fh))


def select(rows, **match):
    def ok(r, k, v):
        return r.get(k, "") in [str(x) for x in v] if isinstance(v, (list, tuple)) else r.get(k, "") == str(v)
    return [r for r in rows if all(ok(r, k, v) for k, v in match.items())]


def stat(rows, col, scale=1.0):
    xs = [float(r[col]) * scale for r in rows if r.get(col, "") != ""]
    if not xs:
        return None, None, 0
    return statistics.mean(xs), (statistics.stdev(xs) if len(xs) > 1 else None), len(xs)


def pm(s, digits=1):
    mean, std, n = s
    if n == 0:
        return r"\missing{n/a}"
    if std is None:
        return f"${mean:.{digits}f}$"
    return f"${mean:.{digits}f} \\pm {std:.{digits}f}$"


def mark_best(body, best):
    def num(cell):
        m = re.match(r"\$(-?\d+(?:\.\d+)?)", cell)
        return float(m.group(1)) if m else None

    groups, cur = [], []
    for i, row in enumerate(body):
        if not isinstance(row, list):
            continue
        if row[0].startswith(r"\multicolumn"):
            groups.append(cur)
            cur = []
        else:
            cur.append(i)
    groups.append(cur)
    for idx in groups:
        for col, how in best.items():
            vals = {i: num(body[i][col]) for i in idx if num(body[i][col]) is not None}
            if not vals:
                continue
            target = (max if how == "max" else min)(vals.values())
            for i, v in vals.items():
                if v == target:
                    body[i][col] = "$\\mathbf{" + body[i][col][1:-1] + "}$"
    return body


def write_table(name, colspec, header, body, source, best=None):
    if best:
        body = mark_best(body, best)

    def line(row):
        return r"\midrule" if row == "midrule" else " & ".join(row) + r" \\"
    out = [f"% Generated by scripts/{source} from data/; do not edit by hand.", rf"\begin{{tabular}}{{{colspec}}}",
           r"\toprule", *map(line, header), r"\midrule", *map(line, body), r"\bottomrule", r"\end{tabular}"]
    TABLES.mkdir(exist_ok=True)
    (TABLES / f"{name}.tex").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"tables/{name}.tex")
